function applyLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  document.documentElement.lang = lang;
  document.title = 'Marco Túlio Costa - ' + (lang === 'pt' ? 'Currículo' : 'Resume');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const text = TRANSLATIONS[lang][el.dataset.i18n];
    if (text !== undefined) {
      el.textContent = text;
      // if the localized element is inside a button, propagate as aria-label/title
      const parent = el.parentElement;
      if (parent && parent.tagName.toLowerCase() === 'button') {
        parent.setAttribute('aria-label', text);
        parent.setAttribute('title', text);
      }
    }
  });
  document.querySelectorAll('[data-lang]').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  localStorage.setItem('resume-lang', lang);
}

function initLang() {
  const saved = localStorage.getItem('resume-lang');
  const preferred = saved || (navigator.language.startsWith('pt') ? 'pt' : 'en');
  applyLang(preferred);
}
